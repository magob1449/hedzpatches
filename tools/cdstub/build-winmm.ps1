#Requires -Version 5.1
<#
.SYNOPSIS
    build-winmm.ps1 - Builds the 32-bit winmm.dll CD-presence stub for H.E.D.Z.

.DESCRIPTION
    1. Copies the 32-bit system winmm.dll (SysWOW64 on x64 Windows) to
       build\winmm_real.dll - this is the "real" DLL all non-intercepted
       exports are forwarded to by the linker.
    2. Parses winmm.dll's PE export table and generates
       winmm_generated.def with forwarding entries for EVERY named export
       except the six the stub implements - so the proxy can never go
       stale against a Windows update.
    3. Locates Visual Studio (vswhere) and compiles winmm_stub.c as a
       32-bit DLL via vcvarsall x86.
    4. Verifies the output (x86 machine type + expected exports).
    5. Optionally deploys winmm.dll + winmm_real.dll to the game folder.

.PARAMETER DeployTo
    Game folder to copy winmm.dll + winmm_real.dll into (e.g. C:\GAMES\HEDZ).
    Omit to only build into tools\cdstub\build\.

.EXAMPLE
    powershell -NoProfile -ExecutionPolicy Bypass -File .\build-winmm.ps1 -DeployTo C:\GAMES\HEDZ
#>
[CmdletBinding()]
param(
    [string]$DeployTo = ''
)

$ErrorActionPreference = 'Stop'
$here  = $PSScriptRoot
$build = Join-Path $here 'build'
New-Item -ItemType Directory -Force -Path $build | Out-Null

Write-Host '=== winmm.dll CD stub build (32-bit) ===' -ForegroundColor Cyan

# ---------- 1. locate the 32-bit system winmm.dll ----------
$sysWinmm = Join-Path $env:windir 'SysWOW64\winmm.dll'    # x64 Windows: 32-bit DLLs live in SysWOW64
if (-not (Test-Path $sysWinmm)) { $sysWinmm = Join-Path $env:windir 'System32\winmm.dll' }  # 32-bit OS
if (-not (Test-Path $sysWinmm)) { throw 'winmm.dll not found under SysWOW64 or System32.' }
Write-Host ("System winmm.dll : {0}" -f $sysWinmm)

$realCopy = Join-Path $build 'winmm_real.dll'
Copy-Item $sysWinmm $realCopy -Force

# ---------- 2. minimal PE export-table parser ----------
function Get-PeExports {
    param([byte[]]$b)
    $lfanew  = [BitConverter]::ToInt32($b, 0x3C)
    $machine = [BitConverter]::ToUInt16($b, $lfanew + 4)
    $nsec    = [BitConverter]::ToUInt16($b, $lfanew + 6)
    $optSize = [BitConverter]::ToUInt16($b, $lfanew + 20)
    $opt     = $lfanew + 24
    $magic   = [BitConverter]::ToUInt16($b, $opt)           # 0x10B = PE32, 0x20B = PE32+
    $dd      = if ($magic -eq 0x20B) { $opt + 112 } else { $opt + 96 }
    $expRva  = [BitConverter]::ToUInt32($b, $dd)

    $result = [pscustomobject]@{ Machine = $machine; Exports = @() }
    if ($expRva -eq 0) { return $result }

    $secTab = $opt + $optSize
    $rva2off = { param($rva)
        for ($i = 0; $i -lt $nsec; $i++) {
            $s  = $secTab + 40 * $i
            $vs = [BitConverter]::ToUInt32($b, $s + 8)
            $va = [BitConverter]::ToUInt32($b, $s + 12)
            $pr = [BitConverter]::ToUInt32($b, $s + 20)
            if ($rva -ge $va -and $rva -lt ($va + [Math]::Max($vs, 1))) { return ($rva - $va + $pr) }
        }
        return -1
    }

    $e = & $rva2off $expRva
    if ($e -lt 0) { return $result }

    $base     = [BitConverter]::ToUInt32($b, $e + 16)
    $numNames = [BitConverter]::ToUInt32($b, $e + 24)
    $namesRva = [BitConverter]::ToUInt32($b, $e + 32)
    $ordsRva  = [BitConverter]::ToUInt32($b, $e + 36)
    $names    = & $rva2off $namesRva
    $ords     = & $rva2off $ordsRva
    if ($names -lt 0 -or $ords -lt 0) { return $result }

    $list = New-Object System.Collections.Generic.List[object]
    for ($i = 0; $i -lt $numNames; $i++) {
        $nRva = [BitConverter]::ToUInt32($b, $names + 4 * $i)
        $nOff = & $rva2off $nRva
        if ($nOff -lt 0) { continue }
        $end = $nOff; while ($end -lt $b.Length -and $b[$end] -ne 0) { $end++ }
        $name = [Text.Encoding]::ASCII.GetString($b, $nOff, $end - $nOff)
        $ord  = [BitConverter]::ToUInt16($b, $ords + 2 * $i) + $base
        $list.Add([pscustomobject]@{ Name = $name; Ordinal = $ord })
    }
    $result.Exports = $list
    return $result
}

$pe = Get-PeExports ([IO.File]::ReadAllBytes($realCopy))
if ($pe.Machine -ne 0x014C) { throw ("System winmm.dll is not 32-bit (machine=0x{0:X4})." -f $pe.Machine) }
Write-Host ("Parsed exports   : {0} named exports" -f $pe.Exports.Count)

# ---------- 3. generate the forwarders source (everything except the six we implement) ----------
$intercept = 'mciSendCommandA','mciSendCommandW','mciSendStringA','mciSendStringW','mciGetDeviceIDA','mciGetDeviceIDW'
$fw = New-Object System.Collections.Generic.List[string]
$fw.Add('/* auto-generated by build-winmm.ps1 - DO NOT EDIT */')
$fw.Add('/* linker export forwarders: every non-intercepted winmm export is')
$fw.Add('   re-exported as Name=winmm_real.Name by the linker itself. */')
$fw.Add('typedef int _forwarders_tu_marker_t;')
foreach ($x in $pe.Exports) {
    if ($intercept -notcontains $x.Name) {
        $fw.Add(('#pragma comment(linker, "/export:{0}=winmm_real.{0}")' -f $x.Name))
    }
}
$fwc = Join-Path $build 'winmm_forwarders.c'
Set-Content -Path $fwc -Value $fw -Encoding ASCII
Write-Host ("Forwarders       : {0}  ({1} forwarded exports)" -f $fwc, ($pe.Exports.Count - $intercept.Count))

# .def for the six locally-implemented exports (def-export strips x86 name
# decoration; a second /DEF also replaces the forwarder pass)
$defLines2 = New-Object System.Collections.Generic.List[string]
$defLines2.Add('LIBRARY winmm')
$defLines2.Add('EXPORTS')
foreach ($name in $intercept) { $defLines2.Add(('  {0}' -f $name)) }
$def = Join-Path $build 'winmm6.def'
Set-Content -Path $def -Value $defLines2 -Encoding ASCII

Copy-Item (Join-Path $here 'winmm_stub.c') $build -Force

# ---------- 4. locate Visual Studio and compile as x86 ----------
$vcvars = $null
$vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer\vswhere.exe'
if (Test-Path $vswhere) {
    $vsPath = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
    if ($vsPath) { $vcvars = Join-Path $vsPath 'VC\Auxiliary\Build\vcvarsall.bat' }
}
if (-not $vcvars -or -not (Test-Path $vcvars)) {
    # scan both Program Files roots for any VC installation (Build Tools install
    # under 'C:\Program Files (x86)\Microsoft Visual Studio\<year>\BuildTools')
    foreach ($root in "${env:ProgramFiles}", "${env:ProgramFiles(x86)}") {
        $vsRoot = Join-Path $root 'Microsoft Visual Studio'
        if (-not (Test-Path $vsRoot)) { continue }
        Get-ChildItem $vsRoot | Where-Object { $_.PSIsContainer } | ForEach-Object {
            Get-ChildItem $_.FullName | Where-Object { $_.PSIsContainer } | ForEach-Object {
                $p = Join-Path $_.FullName 'VC\Auxiliary\Build\vcvarsall.bat'
                if (Test-Path $p) { $vcvars = $p }
            }
        }
    }
}

if (-not $vcvars -or -not (Test-Path $vcvars)) {
    Write-Warning 'Visual Studio C++ tools not found - source and forwarders are ready, build manually:'
    Write-Host ''
    Write-Host '  1. Open the "x86 Native Tools Command Prompt for VS 2022"'
    Write-Host ("  2. cd /d `"$build`"")
    Write-Host '  3. cl /nologo /LD /O2 /W3 /MT winmm_stub.c winmm_forwarders.c /Fe:winmm.dll /link /DEF:winmm6.def /MACHINE:X86 /NODEFAULTLIB:winmm.lib'
    Write-Host ''
    Write-Host '  (Install VS 2022 Community with the "Desktop development with C++" workload to automate this.)'
    return
}

$buildCmd = Join-Path $build 'build.cmd'
@"
@echo off
rem always run from this script's folder so cl finds source + def
cd /d "%~dp0"
rem vcvarsall itself calls vswhere.exe by bare name in some builds:
rem make sure the VS Installer dir is on PATH first.
set "PATH=%ProgramFiles(x86)%\Microsoft Visual Studio\Installer;%PATH%"
call "$vcvars" x86
cl /nologo /LD /O2 /W3 /MT winmm_stub.c winmm_forwarders.c /Fe:winmm.dll /link /DEF:winmm6.def /MACHINE:X86 /NODEFAULTLIB:winmm.lib
"@ | Set-Content -Path $buildCmd -Encoding ASCII

Write-Host 'Compiling (x86 via vcvarsall)...'
# run through cmd.exe with stderr merged into stdout so PowerShell's
# ErrorActionPreference=Stop does not terminate on compiler warning lines
$output = cmd /c "`"$buildCmd`" 2>&1"
$cl = Join-Path $build 'winmm.dll'
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $cl)) {
    $output | Select-Object -Last 25 | ForEach-Object { Write-Host $_ }
    throw 'Build failed - see compiler output above.'
}
$output | Where-Object { $_ -match 'winmm' } | Select-Object -First 6 | ForEach-Object { Write-Host ("  " + $_) }

# ---------- 5. verify the built DLL ----------
$bpe = Get-PeExports ([IO.File]::ReadAllBytes($cl))
if ($bpe.Machine -ne 0x014C) { throw 'Built DLL is not 32-bit - check the toolchain.' }
$names = @($bpe.Exports | ForEach-Object { $_.Name })
foreach ($req in 'mciSendCommandA','mciSendStringA','mciGetDeviceIDA','timeGetTime','joyGetPosEx') {
    if ($names -notcontains $req) { throw ("Expected export missing from built DLL: $req") }
}
Write-Host ("Built OK         : {0}  ({1} exports, x86 verified)" -f $cl, $names.Count) -ForegroundColor Green

# ---------- 6. deploy ----------
if ($DeployTo) {
    if (-not (Test-Path $DeployTo)) { throw "DeployTo folder does not exist: $DeployTo" }
    Copy-Item $cl       $DeployTo -Force
    Copy-Item $realCopy $DeployTo -Force
    Write-Host ("Deployed         : winmm.dll + winmm_real.dll -> {0}" -f $DeployTo) -ForegroundColor Green
    Write-Host 'Revert: delete BOTH files from the game folder.'
    Write-Host 'If the game fails to start after deploying: wrong bitness or missing winmm_real.dll - remove both.'
}
